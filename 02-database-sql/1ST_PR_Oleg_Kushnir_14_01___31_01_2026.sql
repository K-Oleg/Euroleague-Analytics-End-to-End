-- 1st Table creation 'Seasons'
CREATE TABLE Seasons(
Season_ID INT PRIMARY KEY IDENTITY(26, 1),
Season_Name NVARCHAR(20) NOT NULL
);


-- 2nd Table creation 'Teams'
CREATE TABLE Teams (
Team_ID INT PRIMARY KEY IDENTITY(1, 1),
Team_Name VARCHAR(30) NOT NULL
);


-- 3rd Table creation 'Matches'
CREATE TABLE Matches (
Season_ID INT NOT NULL FOREIGN KEY REFERENCES Seasons(Season_ID),
Match_ID INT PRIMARY KEY IDENTITY(1, 1),
[Round] INT NOT NULL,
Home_Team_ID INT NOT NULL,
Away_Team_ID INT NOT NULL,
CONSTRAINT FK_HomeTeam FOREIGN KEY (Home_Team_ID) REFERENCES Teams(Team_ID) ON DELETE NO ACTION,
CONSTRAINT FK_AwayTeam FOREIGN KEY (Away_Team_ID) REFERENCES Teams(Team_ID) ON DELETE NO ACTION,
CONSTRAINT CHK_TeamsDifferent CHECK (Home_Team_ID <> Away_Team_ID)
);


-- 4th Table creation 'Teams Stats'
CREATE TABLE Teams_Stats (
Stats_ID INT PRIMARY KEY IDENTITY(1, 1),
Match_ID INT NOT NULL CONSTRAINT FK_Match_ID  FOREIGN KEY (Match_ID) REFERENCES Matches(Match_ID),
Team_ID INT NOT NULL CONSTRAINT FK_Teams_Stats FOREIGN KEY (Team_ID) REFERENCES Teams(Team_ID),
[2Field_Goals_Made] INT NOT NULL,
[2Field_Goals_Attempts] INT NOT NULL,
[3Field_Goals_Made] INT NOT NULL,
[3Field_Goals_Attempts] INT NOT NULL,
[1Field_Goals_Made] INT NOT NULL,
[1Field_Goals_Attempts] INT NOT NULL,
Offense_Rebounds INT NOT NULL,
Defense_Rebounds INT NOT NULL,
Assists INT NOT NULL,
Steals INT NOT NULL,
Turnovers INT NOT NULL,
Blocks_Made INT NOT NULL,
Blocks_Received INT NOT NULL,
Fouls_Committed INT NOT NULL,
Fouls_Drawn INT NOT NULL,
Points_Made INT NOT NULL,
Points_Received INT NOT NULL,
PIR INT NOT NULL
);


